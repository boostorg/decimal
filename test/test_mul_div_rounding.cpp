// The order of the expected values in each row
constexpr rounding_mode modes[] {rounding_mode::fe_dec_to_nearest,
                                 rounding_mode::fe_dec_to_nearest_from_zero,
                                 rounding_mode::fe_dec_upward,
                                 rounding_mode::fe_dec_downward,
                                 rounding_mode::fe_dec_toward_zero};

// A negative result in a mode is the negative of the result in the mode that goes the other way
constexpr int mirror[] {0, 1, 3, 2, 4};

template <typename T>
struct row
{
    T x;
    T y;
    T expected[5];
};

// Each fast type must give the same result as the type with the same precision
template <typename Fast, typename T, std::size_t N, typename Op>
void test_table(const row<T> (&table)[N], Op op)
{
    for (int i {0}; i < 5; ++i)
    {
        fesetround(modes[i]);

        for (const auto& r : table)
        {
            BOOST_TEST_EQ(op(r.x, r.y), r.expected[i]);
            BOOST_TEST_EQ(op(-r.x, r.y), -r.expected[mirror[i]]);
            BOOST_TEST_EQ(op(r.x, -r.y), -r.expected[mirror[i]]);
            BOOST_TEST_EQ(op(static_cast<Fast>(r.x), static_cast<Fast>(r.y)), static_cast<Fast>(r.expected[i]));
            BOOST_TEST_EQ(op(static_cast<Fast>(-r.x), static_cast<Fast>(r.y)), static_cast<Fast>(-r.expected[mirror[i]]));
        }
    }

    fesetround(rounding_mode::fe_dec_to_nearest);
}

