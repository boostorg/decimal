    test_modes(1500000000000000e-405_DD, 1000000000000001e-8_DD, 1e-398_DD, {1500000000000002e-398_DD, 1500000000000003e-398_DD, 1500000000000003e-398_DD, 1500000000000002e-398_DD, 1500000000000002e-398_DD});
