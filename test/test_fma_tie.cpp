// The sticky step must also hold in constant evaluation.
static_assert(fma(1000001_DF, 1000009_DF, 499991.1_DF) == 1000011e6_DF, "");
static_assert(fma(1000001_DFF, 1000009_DFF, 499991.1_DFF) == 1000011e6_DFF, "");
static_assert(fma(1000000000000001_DD, 1000000000000009_DD, 499999999999991.1_DD) == 1000000000000011e15_DD, "");
static_assert(fma(1000000000000001_DDF, 1000000000000009_DDF, 499999999999991.1_DDF) == 1000000000000011e15_DDF, "");
static_assert(fma(1000000000000000000000000000000001_DL, 1000000000000000000000000000000009_DL, 499999999999999999999999999999991.1_DL) == 1000000000000000000000000000000011e33_DL, "");
static_assert(fma(1000000000000000000000000000000001_DLF, 1000000000000000000000000000000009_DLF, 499999999999999999999999999999991.1_DLF) == 1000000000000000000000000000000011e33_DLF, "");

int main()
{
    test();
    test_sticky_nearest();
    test_finalize_boundary();

    // fesetround has an effect only with the detection of constant evaluation
    #ifndef BOOST_DECIMAL_NO_CONSTEVAL_DETECTION
    fesetround(rounding_mode::fe_dec_to_nearest_from_zero);
    test();
    fesetround(rounding_mode::fe_dec_upward);
    test_sticky_upward();
    fesetround(rounding_mode::fe_dec_downward);
    test_sticky_downward();
    fesetround(rounding_mode::fe_dec_to_nearest);
    #endif

    return boost::report_errors();
}
