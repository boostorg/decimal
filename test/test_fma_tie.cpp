    test_modes(1500000e-104_DF, 1000001e-3_DF, -1e-101_DF, {1500000e-101_DF, 1500001e-101_DF, 1500001e-101_DF, 1500000e-101_DF, 1500000e-101_DF});
    test_modes(1500001e-101_DF, 6499999e-7_DF, 1e-101_DF, {975001e-101_DF, 975001e-101_DF, 975002e-101_DF, 975001e-101_DF, 975001e-101_DF});
    test_modes(-1500001e-101_DF, 6499999e-7_DF, -1e-101_DF, {-975001e-101_DF, -975001e-101_DF, -975001e-101_DF, -975002e-101_DF, -975001e-101_DF});
    test_modes(9999999_DF, 9999999_DF, 1500000e1_DF, {1000000e8_DF, 1000000e8_DF, 1000000e8_DF, 9999999e7_DF, 9999999e7_DF});
