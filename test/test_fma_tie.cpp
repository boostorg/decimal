    test_modes(-1e-51_DF, 1e-51_DF, 1e-101_DF, {1e-101_DF, 1e-101_DF, 1e-101_DF, 0_DF, 0_DF});
    test_modes(1e-51_DF, 1e-51_DF, -1e-101_DF, {-1e-101_DF, -1e-101_DF, -0_DF, -1e-101_DF, -0_DF});
    test_modes(9999999_DFF, 9999999_DFF, 1500000e1_DFF, {1000000e8_DFF, 1000000e8_DFF, 1000000e8_DFF, 9999999e7_DFF, 9999999e7_DFF});
