    test_modes(1234567_DF, 7654321_DF, -9449000e6_DF, {7721140e2_DF, 7721140e2_DF, 7721141e2_DF, 7721140e2_DF, 7721140e2_DF});
    test_modes(-1234567_DF, 7654321_DF, 9449000e6_DF, {-7721140e2_DF, -7721140e2_DF, -7721140e2_DF, -7721141e2_DF, -7721140e2_DF});
    test_modes(2_DF, 3_DF, -6_DF, {0_DF, 0_DF, 0_DF, -0_DF, 0_DF});
