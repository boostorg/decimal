// x * y is a tie at the precision of the result, and z is far below it. In the nearest modes
// the sign of z decides the tie, thus fma must not drop z.
void test()
{
    BOOST_TEST_EQ(fma(7500000e-82_DF, 5304250_DF, -5150000e-105_DF), 3978187e-75_DF);
    BOOST_TEST_EQ(fma(4765625e-11_DF, -5019328e2_DF, 3161063e-25_DF), -2392023e-2_DF);
    BOOST_TEST_EQ(fma(9609375e-8_DFF, -9448768e5_DFF, 5183531e-18_DFF), -9079675e4_DFF);
    BOOST_TEST_EQ(fma(8637847900390625e-4_DD, 3706388133740544e-7_DD, 7822488096645676e-42_DD), 3201521695906349e5_DD);
    BOOST_TEST_EQ(fma(9508819580078125e-12_DDF, 4944725085945856e-24_DDF, 9275094593725324e-82_DDF), 4701849871534545e-20_DDF);

    // Here the even neighbour is the far one for one sign of z only, so each sign checks one mode
    BOOST_TEST_EQ(fma(8637847900390625e-4_DD, 3706388133740544e-7_DD, -7822488096645676e-42_DD), 3201521695906348e5_DD);
    BOOST_TEST_EQ(fma(9508819580078125e-12_DDF, 4944725085945856e-24_DDF, -9275094593725324e-82_DDF), 4701849871534544e-20_DDF);
}

// z moves down to the product and drops a digit, and the sum carries or borrows across the
// last digit. The dropped digit must still decide the rounding of the sum.
void test_sticky_nearest()
{
    BOOST_TEST_EQ(fma(1000001_DF, 1000009_DF, 4999911e-1_DF), 1000011e6_DF);
    BOOST_TEST_EQ(fma(1000001_DF, 1000009_DF, -5000091e-1_DF), 1000009e6_DF);
    BOOST_TEST_EQ(fma(1000001_DFF, 1000009_DFF, 4999911e-1_DFF), 1000011e6_DFF);
    BOOST_TEST_EQ(fma(1000001_DFF, 1000009_DFF, -5000091e-1_DFF), 1000009e6_DFF);
    BOOST_TEST_EQ(fma(1000000000000001_DD, 1000000000000009_DD, 4999999999999911e-1_DD), 1000000000000011e15_DD);
    BOOST_TEST_EQ(fma(1000000000000001_DD, 1000000000000009_DD, -5000000000000091e-1_DD), 1000000000000009e15_DD);
    BOOST_TEST_EQ(fma(1000000000000001_DDF, 1000000000000009_DDF, 4999999999999911e-1_DDF), 1000000000000011e15_DDF);
    BOOST_TEST_EQ(fma(1000000000000001_DDF, 1000000000000009_DDF, -5000000000000091e-1_DDF), 1000000000000009e15_DDF);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DL, 1000000000000000000000000000000009_DL, 4999999999999999999999999999999911e-1_DL), 1000000000000000000000000000000011e33_DL);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DL, 1000000000000000000000000000000009_DL, -5000000000000000000000000000000091e-1_DL), 1000000000000000000000000000000009e33_DL);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DLF, 1000000000000000000000000000000009_DLF, 4999999999999999999999999999999911e-1_DLF), 1000000000000000000000000000000011e33_DLF);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DLF, 1000000000000000000000000000000009_DLF, -5000000000000000000000000000000091e-1_DLF), 1000000000000000000000000000000009e33_DLF);
}

void test_sticky_upward()
{
    BOOST_TEST_EQ(fma(1000001_DF, 1000009_DF, 9999911e-1_DF), 1000012e6_DF);
    BOOST_TEST_EQ(fma(1000001_DFF, 1000009_DFF, 9999911e-1_DFF), 1000012e6_DFF);
    BOOST_TEST_EQ(fma(1000000000000001_DD, 1000000000000009_DD, 9999999999999911e-1_DD), 1000000000000012e15_DD);
    BOOST_TEST_EQ(fma(1000000000000001_DDF, 1000000000000009_DDF, 9999999999999911e-1_DDF), 1000000000000012e15_DDF);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DL, 1000000000000000000000000000000009_DL, 9999999999999999999999999999999911e-1_DL), 1000000000000000000000000000000012e33_DL);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DLF, 1000000000000000000000000000000009_DLF, 9999999999999999999999999999999911e-1_DLF), 1000000000000000000000000000000012e33_DLF);
}

void test_sticky_downward()
{
    BOOST_TEST_EQ(fma(1000001_DF, 1000009_DF, -91e-1_DF), 1000009e6_DF);
    BOOST_TEST_EQ(fma(1000001_DFF, 1000009_DFF, -91e-1_DFF), 1000009e6_DFF);
    BOOST_TEST_EQ(fma(1000000000000001_DD, 1000000000000009_DD, -91e-1_DD), 1000000000000009e15_DD);
    BOOST_TEST_EQ(fma(1000000000000001_DDF, 1000000000000009_DDF, -91e-1_DDF), 1000000000000009e15_DDF);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DL, 1000000000000000000000000000000009_DL, -91e-1_DL), 1000000000000000000000000000000009e33_DL);
    BOOST_TEST_EQ(fma(1000000000000000000000000000000001_DLF, 1000000000000000000000000000000009_DLF, -91e-1_DLF), 1000000000000000000000000000000009e33_DLF);
}

// The expected values are in the order nearest, nearest from zero, upward, downward and
// toward zero.
template <typename T>
void test_modes(T x, T y, T z, const T (&expected)[5])
{
    // fesetround has an effect only with the detection of constant evaluation
    #ifdef BOOST_DECIMAL_NO_CONSTEVAL_DETECTION
    constexpr int mode_count {1};
    #else
    constexpr int mode_count {5};
    #endif

    constexpr rounding_mode modes[] {rounding_mode::fe_dec_to_nearest, rounding_mode::fe_dec_to_nearest_from_zero,
                                     rounding_mode::fe_dec_upward, rounding_mode::fe_dec_downward,
                                     rounding_mode::fe_dec_toward_zero};

    for (int i {}; i < mode_count; ++i)
    {
        fesetround(modes[i]);
        const auto result {fma(x, y, z)};
        BOOST_TEST_EQ(result, expected[i]);
        BOOST_TEST_EQ(signbit(result), signbit(expected[i]));
    }

    fesetround(rounding_mode::fe_dec_to_nearest);
}

