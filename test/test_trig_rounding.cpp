// sin, cos and tan must give the correctly rounded value, also for large arguments and in the
// directed rounding modes. The expected values come from MPFR at 600 bits.

#include <boost/decimal.hpp>
#include <boost/core/lightweight_test.hpp>
#include <limits>

using namespace boost::decimal;
using namespace boost::decimal::literals;

// Each type has inputs near pi/2, pi and 1000*pi/2, the value nearest to a multiple of pi/2 in its exponent
// range (4.327189e+48 for decimal32_t) and below 10^19 (76.96902), the inputs on each side of 10^19, -10^19 and 10^-80.
template <typename T>
void check(const T x, const T s, const T c, const T t)
{
    BOOST_TEST_EQ(sin(x), s);
    BOOST_TEST_EQ(cos(x), c);
    BOOST_TEST_EQ(tan(x), t);
}

