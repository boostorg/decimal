// Over adjacent inputs where the exact sin and cos go in the directions sin_dir and cos_dir and tan
// goes up, the results must not go the other way. Equal results are correct rounding.
template <typename T>
void check_chain(const T start, const int steps, const int sin_dir, const int cos_dir)
{
    const rounding_mode modes[] {rounding_mode::fe_dec_to_nearest, rounding_mode::fe_dec_upward, rounding_mode::fe_dec_downward};

    for (const auto mode : modes)
    {
        fesetround(mode);

        T a {start};
        T sa {sin(a)};
        T ca {cos(a)};
        T ta {tan(a)};
        for (int i {}; i < steps; ++i)
        {
            const T b {nextafter(a, (std::numeric_limits<T>::max)())};
            const T sb {sin(b)};
            const T cb {cos(b)};
            const T tb {tan(b)};

            BOOST_TEST(sin_dir > 0 ? sb >= sa : sb <= sa);
            BOOST_TEST(cos_dir > 0 ? cb >= ca : cb <= ca);
            BOOST_TEST(tb >= ta);

            a = b;
            sa = sb;
            ca = cb;
            ta = tb;
        }

        fesetround(rounding_mode::fe_dec_to_nearest);
    }
}

// The chains cross the change of method at pi/4, and end 100 steps below pi/2, pi and 5*pi/2.
template <typename T>
void test_monotonic(const T quarter_pi, const T half_pi, const T pi, const T five_half_pi)
{
    const auto back = [](T x, const int n)
    {
        for (int i {}; i < n; ++i)
        {
            x = nextafter(x, T{0});
        }
        return x;
    };

    constexpr int steps {200};
    check_chain(back(quarter_pi, steps / 2), steps, 1, -1);
    check_chain(back(half_pi, steps + 100), steps, 1, -1);
    check_chain(back(pi, steps + 100), steps, -1, -1);
    check_chain(back(five_half_pi, steps + 100), steps, 1, -1);
}

// sin and cos of an infinity are NaN, as tan already is.
template <typename T>
void test_special()
{
    #ifndef BOOST_DECIMAL_FAST_MATH
    const T inf {std::numeric_limits<T>::infinity()};

    BOOST_TEST(isnan(sin(inf)));
    BOOST_TEST(isnan(sin(-inf)));
    BOOST_TEST(isnan(cos(inf)));
    BOOST_TEST(isnan(cos(-inf)));
    BOOST_TEST(isnan(tan(inf)));
    BOOST_TEST(isnan(sin(std::numeric_limits<T>::quiet_NaN())));
    #endif
    BOOST_TEST(signbit(sin(-T{0})));
    BOOST_TEST(signbit(tan(-T{0})));
    BOOST_TEST_EQ(cos(-T{0}), T{1});
}

