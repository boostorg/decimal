// The expected values are the MPFR values rounded to the type. Near 1 the old code
// lost most digits, so a relative error of one epsilon still separates the two.
template <typename T>
void check(const T x, const T expected_log, const T expected_log10, const T expected_log2)
{
    constexpr T eps {std::numeric_limits<T>::epsilon()};
    BOOST_TEST_LE(abs(log(x) - expected_log), eps * abs(expected_log));
    BOOST_TEST_LE(abs(log10(x) - expected_log10), eps * abs(expected_log10));
    BOOST_TEST_LE(abs(log2(x) - expected_log2), eps * abs(expected_log2));
}

