// hi + lo is the MPFR value to twice the precision of T. The old asin, acos, atan and atan2 were off
// by 1 to 1e18 ulps at these points; the error must now stay below one ulp.
template <typename T>
void check(const T got, const T hi, const T lo)
{
    const T ulp {abs(nextafter(hi, hi * 2) - hi)};
    BOOST_TEST_LT(abs((got - hi) - lo), ulp);
}

// Walk 400 consecutive values around each start; asin and atan must not decrease, acos must
// not increase. The starts are the points where the formulas change, and points between them.
template <typename T>
void check_monotone()
{
    const T up {std::numeric_limits<T>::max()};
    const T down {std::numeric_limits<T>::lowest()};
    const T h {numbers::pi_v<T> / 4 - T {5, -1}};
    const T starts[] {
        // asin and acos: +-0.5, s = 0.1 and s = 0.05 where s + s starts to round, and pi/4 - s = 0.5
        T {-5, -1}, T {5, -1}, T {-98, -2}, T {98, -2}, T {-995, -3}, T {995, -3}, 1 - 2 * h * h,
        // atan: the breakpoints 7/16, 11/16, 19/16 and 39/16, and the points where |q| = 0.1
        T {4375, -4}, T {6875, -4}, T {11875, -4}, T {24375, -4}, T {12} / 19, T {9} / 11, T {28} / 23, T {32} / 17,
        T {-9, -1}, T {-75, -2}, T {-6, -1}, T {75, -2}, T {2, 0}, T {236, -2}};
    for (const T start : starts)
    {
        T x {start};
        for (int i {}; i < 200; ++i)
        {
            x = nextafter(x, down);
        }
        for (int i {}; i < 400; ++i)
        {
            const T next {nextafter(x, up)};
            if (abs(next) <= 1)
            {
                BOOST_TEST_LE(asin(x), asin(next));
                BOOST_TEST_GE(acos(x), acos(next));
            }
            BOOST_TEST_LE(atan(x), atan(next));
            x = next;
        }
    }
}

// atan2 must return pi/2, 3 pi/4 and pi/4 rounded once to T, as asin and atan do
template <typename T>
void check_atan2()
{
    const T half_pi {static_cast<T>(1.570796326794896619231321691639751_DL)};
    const T one {1};
    const T zero {0};
    BOOST_TEST_EQ(atan2(one, zero), half_pi);
    BOOST_TEST_EQ(atan2(-one, zero), -half_pi);
    BOOST_TEST_EQ(asin(one), half_pi);
    #ifndef BOOST_DECIMAL_FAST_MATH
    const T inf {std::numeric_limits<T>::infinity()};
    BOOST_TEST_EQ(atan(inf), half_pi);
    BOOST_TEST_EQ(atan2(inf, one), half_pi);
    BOOST_TEST_EQ(atan2(inf, inf), static_cast<T>(0.7853981633974483096156608458198757_DL));
    BOOST_TEST_EQ(atan2(inf, -inf), static_cast<T>(2.356194490192344928846982537459627_DL));
    #endif
}

